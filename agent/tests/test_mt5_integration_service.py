        result = bridge_service.create_execution_log("test-user-123", pending_log)
        assert result is not None
        assert result["status"] == "PENDING"

        # Step 2: Query execution logs - ID will be generated by service
        logs = bridge_service.get_user_logs("test-user-123", limit=10)
        assert len(logs) == 1
        # Just verify it's a valid UUID format, not the original ID
